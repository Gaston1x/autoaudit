from dotenv import load_dotenv  # noqa: E402

load_dotenv(RAIZ / ".env")

CRED = {
    "admin": (os.getenv("AA_USUARIO", "aa_admin"), os.getenv("AA_CLAVE", "AutoAudit.Admin1")),
    "lector": (os.getenv("AA_LECTOR_USUARIO", "aa_lector"), os.getenv("AA_LECTOR_CLAVE", "AutoAudit.Lector1")),
    "cajero1": (os.getenv("AA_NEGOCIO_USUARIO", "cajero1"), os.getenv("AA_NEGOCIO_CLAVE", "Cajero.Uno1")),
    "cajero2": (os.getenv("AA_NEGOCIO2_USUARIO", "cajero2"), os.getenv("AA_NEGOCIO2_CLAVE", "Cajero.Dos2")),
}


