"""AutoAudit - pruebas de rendimiento con volumen creciente de registros auditados.

Crea una base de datos aparte (autoaudit_perf), instala AutoAudit y compara dos
tablas idénticas: una SIN auditoría y otra CON el trigger generado.

Mide, para volúmenes crecientes:
  1. Operaciones masivas (INSERT, UPDATE y DELETE de N filas en una sentencia).
  2. Operaciones individuales (una fila por transacción, el caso típico OLTP).
  3. Tiempo de las consultas históricas a medida que crece la bitácora.

Resultados en docs/rendimiento/ (CSV, Markdown y gráfica PNG).

Uso:  python pruebas_rendimiento.py [--volumenes 1000 10000 100000] [--individuales 2000]
"""

import argparse
import csv
import statistics
import subprocess
import time
from pathlib import Path

import psycopg
from psycopg.rows import dict_row

RAIZ = Path(__file__).resolve().parent
SALIDA = RAIZ / "docs" / "rendimiento"
DB = "autoaudit_perf"

TABLA_DDL = """
CREATE TABLE perf.{nombre} (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  text NOT NULL,
    monto   numeric(12,2) NOT NULL,
    estado  text NOT NULL,
    nota    text
)"""


def preparar() -> None:
    subprocess.run(["dropdb", "--if-exists", "--force", DB], check=True)
    subprocess.run(["createdb", DB], check=True)
    subprocess.run(["psql", "-q", "-X", "-d", DB, "-v", "demo=0", "-f", str(RAIZ / "sql" / "instalar.sql")],
                   check=True, capture_output=True)
    with psycopg.connect(dbname=DB, autocommit=True) as c:
        c.execute("""DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'demo_owner')
                     THEN CREATE ROLE demo_owner NOLOGIN; END IF; END $$""")
        c.execute("GRANT demo_owner TO autoaudit_owner")
        c.execute("CREATE SCHEMA perf AUTHORIZATION demo_owner")
        c.execute("SET ROLE demo_owner")
        c.execute(TABLA_DDL.format(nombre="sin_auditoria"))
        c.execute(TABLA_DDL.format(nombre="con_auditoria"))
        c.execute("RESET ROLE")
        c.execute("""SELECT autoaudit.fn_configurar_tabla('perf', 'con_auditoria',
                     '{"nombre": ["I","U","D"], "monto": ["I","U","D"], "estado": ["I","U","D"]}')""")


def cronometrar(conn, sql: str, params=None) -> float:
    t0 = time.perf_counter()
    with conn.transaction():
        conn.execute(sql, params)
    return (time.perf_counter() - t0) * 1000


def masivo(conn, tabla: str, n: int) -> dict[str, float]:
    conn.execute(f"TRUNCATE perf.{tabla} RESTART IDENTITY")
    return {
        "insert": cronometrar(conn, f"""INSERT INTO perf.{tabla} (nombre, monto, estado, nota)
                                         SELECT 'Cliente ' || g, g * 1.5, 'ACTIVO', 'nota' FROM generate_series(1, %s) g""", (n,)),
        "update": cronometrar(conn, f"UPDATE perf.{tabla} SET monto = monto + 1, estado = 'REVISADO'"),
        "delete": cronometrar(conn, f"DELETE FROM perf.{tabla}"),
    }


def individuales(conn, tabla: str, n: int) -> float:
    """Latencia promedio (ms) de INSERT + UPDATE de una fila, cada uno en su propia transacción."""
    conn.execute(f"TRUNCATE perf.{tabla} RESTART IDENTITY")
    tiempos = []
    for i in range(n):
        t0 = time.perf_counter()
        conn.execute(f"INSERT INTO perf.{tabla} (nombre, monto, estado) VALUES (%s, %s, 'ACTIVO')", (f"C{i}", i))
        conn.execute(f"UPDATE perf.{tabla} SET monto = monto + 1 WHERE id = %s", (i + 1,))
        tiempos.append((time.perf_counter() - t0) * 1000)
    return statistics.mean(tiempos)


def consultas(conn) -> dict[str, float]:
    """Consultas históricas puntuales sobre una bitácora cada vez más grande."""
    def medir(sql, params, repeticiones=5):
        valores = []
        for _ in range(repeticiones):
            t0 = time.perf_counter()
            conn.execute(sql, params).fetchall()
            valores.append((time.perf_counter() - t0) * 1000)
        return statistics.median(valores)

    return {
        "historial_registro": medir("SELECT * FROM autoaudit.fn_historial_registro('perf', 'con_auditoria', %s)",
                                    ('{"id": 7}',)),
        "por_usuario_dia": medir("""SELECT count(*) FROM autoaudit.fn_cambios_por_usuario(
                                        'usuario_raro', now() - interval '1 day', now() + interval '1 day')""", None),
        # Columna "nombre" en UPDATE: la prueba nunca la modifica; mide la búsqueda por índice.
        "por_columna_rango": medir("""SELECT count(*) FROM autoaudit.fn_cambios_por_columna(
                                        'perf', 'con_auditoria', 'nombre', NULL, NULL, 'UPDATE')""", None),
    }


def tamano_bitacora(conn) -> tuple[int, int]:
    f = conn.execute("""SELECT (SELECT count(*) FROM autoaudit.aud_bitacora) AS cab,
                               (SELECT count(*) FROM autoaudit.aud_bitacora_detalle) AS det""").fetchone()
    return f["cab"], f["det"]


def graficar(filas: list[dict], latencia: dict, archivo: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    vol = [f["volumen"] for f in filas]
    fig, ejes = plt.subplots(1, 3, figsize=(16, 4.6))
    colores = {"insert": "#198754", "update": "#0d6efd", "delete": "#dc3545"}

    ax = ejes[0]
    for op, color in colores.items():
        ax.plot(vol, [f[f"{op}_sin_us"] for f in filas], "--", color=color, alpha=.6, label=f"{op.upper()} sin auditoría")
        ax.plot(vol, [f[f"{op}_con_us"] for f in filas], "-o", color=color, label=f"{op.upper()} con auditoría")
    ax.set_xscale("log"); ax.set_xlabel("Filas por operación"); ax.set_ylabel("µs por fila")
    ax.set_title("Costo por fila en operaciones masivas"); ax.legend(fontsize=7); ax.grid(alpha=.3)

    ax = ejes[1]
    ax.bar(["Sin auditoría", "Con auditoría"], [latencia["sin"], latencia["con"]], color=["#adb5bd", "#1f4e79"])
    for i, v in enumerate([latencia["sin"], latencia["con"]]):
        ax.text(i, v, f"{v:.2f} ms", ha="center", va="bottom")
    ax.set_ylabel("ms por transacción (INSERT + UPDATE)")
    ax.set_title(f"Operación individual (+{latencia['con'] - latencia['sin']:.2f} ms)"); ax.grid(axis="y", alpha=.3)

    ax = ejes[2]
    filas_bit = [f["bitacora_detalle"] for f in filas]
    for clave, etiqueta in (("q_historial_registro", "Historial de un registro"),
                            ("q_por_usuario_dia", "Por usuario (1 día)"),
                            ("q_por_columna_rango", "Por columna y operación")):
        ax.plot(filas_bit, [f[clave] for f in filas], "-o", label=etiqueta)
    ax.set_xscale("log"); ax.set_xlabel("Filas en la bitácora (detalle)"); ax.set_ylabel("ms")
    ax.set_title("Consultas históricas vs. tamaño de la bitácora"); ax.legend(fontsize=8); ax.grid(alpha=.3)

    fig.suptitle("AutoAudit - pruebas de rendimiento (PostgreSQL 18)", fontweight="bold")
    fig.tight_layout()
    fig.savefig(archivo, dpi=130)


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--volumenes", type=int, nargs="+", default=[1000, 5000, 10000, 50000, 100000])
    p.add_argument("--individuales", type=int, default=2000)
    args = p.parse_args()
    SALIDA.mkdir(parents=True, exist_ok=True)

    print("Preparando base de datos", DB)
    preparar()
    filas = []
    with psycopg.connect(dbname=DB, autocommit=True, row_factory=dict_row) as conn:
        version = conn.execute("SHOW server_version").fetchone()["server_version"]
        masivo(conn, "con_auditoria", 500)  # calentamiento
        masivo(conn, "sin_auditoria", 500)
        # Usuario de carga masiva excluido de la auditoría (aud_usuario.auditar = false).
        conn.execute("SELECT autoaudit.fn_registrar_usuario(session_user, 'carga_masiva', false)")
        for n in args.volumenes:
            sin = masivo(conn, "sin_auditoria", n)
            con = masivo(conn, "con_auditoria", n)
            conn.execute("SET autoaudit.usuario_app = 'carga_masiva'")
            exc = masivo(conn, "con_auditoria", n)
            conn.execute("RESET autoaudit.usuario_app")
            cab, det = tamano_bitacora(conn)
            q = consultas(conn)
            fila = {"volumen": n, "bitacora_operaciones": cab, "bitacora_detalle": det}
            for op in ("insert", "update", "delete"):
                fila[f"{op}_sin_ms"] = round(sin[op], 1)
                fila[f"{op}_con_ms"] = round(con[op], 1)
                fila[f"{op}_exc_ms"] = round(exc[op], 1)
                fila[f"{op}_sin_us"] = round(sin[op] * 1000 / n, 2)
                fila[f"{op}_con_us"] = round(con[op] * 1000 / n, 2)
            fila.update({f"q_{k}": round(v, 2) for k, v in q.items()})
            filas.append(fila)
            print(f"N={n:>7}: INSERT {sin['insert']:8.1f} -> {con['insert']:8.1f} ms | "
                  f"UPDATE {sin['update']:8.1f} -> {con['update']:8.1f} ms | "
                  f"DELETE {sin['delete']:8.1f} -> {con['delete']:8.1f} ms | bitácora {det} filas | "
                  f"consultas {q}")

        # synchronous_commit = off: se mide el costo del trigger, no la escritura a disco del COMMIT.
        conn.execute("SET synchronous_commit = off")
        individuales(conn, "con_auditoria", 200)  # calentamiento
        latencia = {"sin": individuales(conn, "sin_auditoria", args.individuales),
                    "con": individuales(conn, "con_auditoria", args.individuales)}
        print(f"Individual (INSERT+UPDATE): sin {latencia['sin']:.3f} ms, con {latencia['con']:.3f} ms")

    with open(SALIDA / "resultados.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(filas[0].keys()))
        w.writeheader()
        w.writerows(filas)
    graficar(filas, latencia, SALIDA / "rendimiento.png")

    md = [f"# Resultados de rendimiento\n", f"PostgreSQL {version}. Tabla con 5 columnas; se auditan 3 columnas en INSERT, UPDATE y DELETE.\n",
          "## Operaciones masivas (una sentencia sobre N filas)\n",
          "Columnas: sin auditoría / con auditoría / con auditoría pero usuario de carga masiva excluido.\n",
          "| Filas | INSERT (ms) | UPDATE (ms) | DELETE (ms) | µs extra por fila (INSERT) | Filas en bitácora (detalle) |",
          "|---:|---:|---:|---:|---:|---:|"]
    for f in filas:
        md.append(f"| {f['volumen']:,} | {f['insert_sin_ms']} / {f['insert_con_ms']} / {f['insert_exc_ms']} | "
                  f"{f['update_sin_ms']} / {f['update_con_ms']} / {f['update_exc_ms']} | "
                  f"{f['delete_sin_ms']} / {f['delete_con_ms']} / {f['delete_exc_ms']} | "
                  f"{f['insert_con_us'] - f['insert_sin_us']:.1f} | {f['bitacora_detalle']:,} |")
    md += ["", "## Operación individual (caso típico de una aplicación)\n",
           f"Promedio de {args.individuales} transacciones de INSERT + UPDATE de una fila:\n",
           f"- Sin auditoría: **{latencia['sin']:.3f} ms**",
           f"- Con auditoría: **{latencia['con']:.3f} ms** (+{latencia['con'] - latencia['sin']:.3f} ms por transacción)\n",
           "## Consultas históricas a medida que crece la bitácora (mediana, ms)\n",
           "| Filas en bitácora | Historial de un registro | Por usuario (1 día) | Por columna y operación |",
           "|---:|---:|---:|---:|"]
    for f in filas:
        md.append(f"| {f['bitacora_detalle']:,} | {f['q_historial_registro']} | {f['q_por_usuario_dia']} | {f['q_por_columna_rango']} |")
    md += ["", "![Gráfica de rendimiento](rendimiento.png)", ""]
    (SALIDA / "resultados.md").write_text("\n".join(md), encoding="utf-8")
    print("Resultados en", SALIDA)


if __name__ == "__main__":
    main()
