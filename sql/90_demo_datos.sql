-- AutoAudit - 90_demo_datos.sql
-- Esquema de negocio de ejemplo ("demo": una pequeña tienda) y usuarios de prueba.
-- Las contraseñas son SOLO para el entorno de pruebas local (ver .env.example).
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Roles de prueba
-- -----------------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'demo_owner') THEN
        CREATE ROLE demo_owner NOLOGIN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'aa_admin') THEN
        CREATE ROLE aa_admin LOGIN PASSWORD 'AutoAudit.Admin1';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'aa_lector') THEN
        CREATE ROLE aa_lector LOGIN PASSWORD 'AutoAudit.Lector1';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'cajero1') THEN
        CREATE ROLE cajero1 LOGIN PASSWORD 'Cajero.Uno1';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'cajero2') THEN
        CREATE ROLE cajero2 LOGIN PASSWORD 'Cajero.Dos2';
    END IF;
END
$$;

GRANT autoaudit_admin  TO aa_admin;
GRANT autoaudit_lector TO aa_lector;

-- AutoAudit necesita ser miembro del dueño de las tablas de negocio para
-- crear/eliminar sus triggers (requisito de PostgreSQL para DROP TRIGGER).
GRANT demo_owner TO autoaudit_owner;

-- -----------------------------------------------------------------------------
-- Esquema de negocio
-- -----------------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS demo AUTHORIZATION demo_owner;

SET ROLE demo_owner;

CREATE TABLE IF NOT EXISTS demo.clientes (
    id         integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nit        varchar(15)  NOT NULL UNIQUE,
    nombre     varchar(120) NOT NULL,
    correo     varchar(120),
    telefono   varchar(20),
    limite_credito numeric(12,2) NOT NULL DEFAULT 0,
    creado     timestamptz  NOT NULL DEFAULT now()
);
COMMENT ON TABLE demo.clientes IS 'Clientes de la tienda (tabla de ejemplo)';

CREATE TABLE IF NOT EXISTS demo.productos (
    id         integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo     varchar(20)  NOT NULL UNIQUE,
    descripcion varchar(200) NOT NULL,
    precio     numeric(12,2) NOT NULL CHECK (precio >= 0),
    existencia integer      NOT NULL DEFAULT 0,
    activo     boolean      NOT NULL DEFAULT true,
    atributos  jsonb        NOT NULL DEFAULT '{}'
);
COMMENT ON TABLE demo.productos IS 'Catálogo de productos (tabla de ejemplo)';

CREATE TABLE IF NOT EXISTS demo.ventas (
    id          integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id  integer      NOT NULL REFERENCES demo.clientes (id),
    fecha       timestamptz  NOT NULL DEFAULT now(),
    total       numeric(12,2) NOT NULL DEFAULT 0,
    estado      varchar(15)  NOT NULL DEFAULT 'ABIERTA'
);
COMMENT ON TABLE demo.ventas IS 'Encabezado de ventas (tabla de ejemplo)';

CREATE TABLE IF NOT EXISTS demo.venta_detalle (
    venta_id    integer      NOT NULL REFERENCES demo.ventas (id) ON DELETE CASCADE,
    linea       smallint     NOT NULL,
    producto_id integer      NOT NULL REFERENCES demo.productos (id),
    cantidad    integer      NOT NULL CHECK (cantidad > 0),
    precio      numeric(12,2) NOT NULL,
    PRIMARY KEY (venta_id, linea)
);
COMMENT ON TABLE demo.venta_detalle IS 'Detalle de ventas, llave primaria compuesta (tabla de ejemplo)';

GRANT USAGE ON SCHEMA demo TO cajero1, cajero2, aa_admin, aa_lector;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA demo TO cajero1, cajero2;
GRANT SELECT ON ALL TABLES IN SCHEMA demo TO aa_admin, aa_lector;

